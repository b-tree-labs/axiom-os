"""/init [--yes]: create or refresh the project's AGENTS.md without clobbering it (ADR-168).

AGENTS.md is the primary instruction file; ``CLAUDE.md`` is a symlink to it by repo convention, so one file
serves every harness. This command owns exactly one region, between ``<!-- axiom:init:begin -->`` and
``<!-- axiom:init:end -->``, holding facts read from the project (manifests, top-level directories). It never
touches anything outside that region, and it leaves the cross-mem managed block
(``<!-- axiom:cross-mem:begin -->``, written by ``memory.sync.writeback``) alone: that block has its own
markers and its own writer.

- file absent: created from the bundled ``templates/AGENTS.md`` (and ``CLAUDE.md`` linked to it when free).
- file present: the change is shown as a diff and nothing is written until ``/init --yes``.
"""

from __future__ import annotations

import difflib
import os
from dataclasses import dataclass
from pathlib import Path

from axiom.memory.rendering import splice_marked_block

from ..command_registry import CommandContext, command

BEGIN = "<!-- axiom:init:begin -->"
END = "<!-- axiom:init:end -->"
TEMPLATE = Path(__file__).parent / "templates" / "AGENTS.md"

#: A manifest file and the thing it tells you. Only what exists is reported: nothing is inferred.
_MANIFESTS = {
    "pyproject.toml": "Python project (pyproject.toml)",
    "setup.py": "Python project (setup.py)",
    "package.json": "Node project (package.json)",
    "Cargo.toml": "Rust crate (Cargo.toml)",
    "go.mod": "Go module (go.mod)",
    "pom.xml": "Maven project (pom.xml)",
    "build.gradle": "Gradle project (build.gradle)",
    "Makefile": "Makefile present",
    "Dockerfile": "Dockerfile present",
}
_SKIP_DIRS = {"node_modules", "__pycache__", "dist", "build", "venv"}


def _cli() -> str:
    try:
        from axiom.infra.branding import get_branding

        return get_branding().cli_name
    except Exception:  # noqa: BLE001
        return "axi"


def build_block(root: Path) -> str:
    """The managed region: deterministic for a given tree, so a second run is a no-op."""
    facts = [desc for name, desc in _MANIFESTS.items() if (root / name).is_file()]
    dirs = sorted(
        p.name for p in root.iterdir()
        if p.is_dir() and not p.name.startswith(".") and p.name not in _SKIP_DIRS
    )
    lines = [BEGIN, "## Project facts", "",
             f"_Generated by `{_cli()} /init` from the tree; regenerate with `/init --yes`._", ""]
    lines += [f"- {f}" for f in facts] or ["- No build manifest found at the project root."]
    if dirs:
        shown = dirs[:15]
        more = f" (+{len(dirs) - 15} more)" if len(dirs) > 15 else ""
        lines.append("- Top-level directories: " + ", ".join(f"`{d}/`" for d in shown) + more)
    lines += [END]
    return "\n".join(lines)


@dataclass(frozen=True)
class InitPlan:
    path: Path
    kind: str  # create | update | unchanged | refuse
    new_text: str
    diff: str = ""
    reason: str = ""


def plan_init(root: Path) -> InitPlan:
    path = root / "AGENTS.md"
    block = build_block(root)
    if not path.exists():
        text = (TEMPLATE.read_text(encoding="utf-8")
                .replace("$PROJECT", root.resolve().name)
                .replace("$CLI", _cli())
                .replace("$BLOCK", block))
        return InitPlan(path, "create", text)
    existing = path.read_text(encoding="utf-8")
    if existing.count(BEGIN) != existing.count(END) or existing.count(BEGIN) > 1 or (
        BEGIN in existing and existing.index(BEGIN) > existing.index(END)
    ):
        return InitPlan(path, "refuse", existing,
                        reason=f"the {BEGIN} / {END} markers in {path.name} are unbalanced; fix them by hand")
    new = splice_marked_block(existing, block, begin=BEGIN, end=END)
    if new == existing:
        return InitPlan(path, "unchanged", existing)
    diff = "".join(difflib.unified_diff(
        existing.splitlines(keepends=True), new.splitlines(keepends=True),
        fromfile="AGENTS.md (current)", tofile="AGENTS.md (after /init)"))
    return InitPlan(path, "update", new, diff)


def _write(path: Path, text: str) -> None:
    target = path.resolve() if path.is_symlink() else path  # write through a symlink, never replace it
    tmp = target.with_name(target.name + ".init-tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, target)


def _link_claude_md(root: Path) -> str:
    link = root / "CLAUDE.md"
    if link.exists() or link.is_symlink():
        return "" if link.is_symlink() else "  CLAUDE.md already exists as a regular file and was left alone.\n"
    link.symlink_to("AGENTS.md")
    return "  Linked CLAUDE.md -> AGENTS.md.\n"


def _project_root() -> Path:
    from axiom.infra.paths import get_project_root

    return get_project_root()


@command("/init", "Create or refresh AGENTS.md between managed markers (/init [--yes])", "Agent",
         usage="/init [--yes]", subcommands={"--yes": "Apply the shown change"}, mutates=True)
def _init(ctx: CommandContext, args: list[str]) -> str:
    unknown = [a for a in args if a != "--yes"]
    if unknown:
        return f"\n  /init: unknown option {unknown[0]}. Usage: /init [--yes]\n"
    root = _project_root()
    plan = plan_init(root)
    if plan.kind == "refuse":
        return f"\n  /init: {plan.reason}. Nothing was written.\n"
    if plan.kind == "unchanged":
        return f"\n  {plan.path.name} is already up to date; nothing to do.\n"
    if plan.kind == "create":
        _write(plan.path, plan.new_text)
        return f"\n  Created {plan.path} from the bundled template.\n{_link_claude_md(root)}"
    if "--yes" not in args:
        return (f"\n  {plan.path.name} exists. /init would change only the region between its "
                f"axiom:init markers:\n\n{plan.diff}\n  Nothing written. Run /init --yes to apply.\n")
    _write(plan.path, plan.new_text)
    return f"\n  Updated the managed region of {plan.path}; nothing outside it changed.\n"
